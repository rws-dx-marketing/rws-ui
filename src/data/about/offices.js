// Phone numbers ship masked and base64'd for scripts/phone-reveal.js.
export const encodePhone = (number) => Buffer.from(number, 'utf8').toString('base64')

// "+86 10 5603 8049 (IP Solutions)" -> { number, label }. The offices that list
// two numbers put the division in a trailing bracket; splitting it off keeps it
// out of the tel: link and lets the template hide it until the reveal.
// Anchored to the end of the string so "+27 (0) 83 654 2011" is left alone.
export const splitPhone = (entry) => {
	const [, number, label] = entry.match(/^(.*?)\s*\(([^)]*)\)$/) ?? []
	return label ? { number, label } : { number: entry, label: '' }
}

// Emails carry their division inconsistently — some prefix it ("Trados: …"),
// some suffix it in brackets like the phone numbers do. Normalised here so the
// template can render one shape: address first, label after.
export const splitEmail = (entry) => {
	const suffix = entry.match(/^(\S+@\S+)\s*\(([^)]*)\)$/)
	if (suffix) return { address: suffix[1], label: suffix[2] }

	const prefix = entry.match(/^(.*?):\s*(\S+@\S+)$/)
	if (prefix) return { address: prefix[2], label: prefix[1] }

	return { address: entry, label: '' }
}

// Dialling code and area code stay readable, so a user can tell the office is
// the right country before spending a click.
//
// Masks runs of digits rather than space-separated words, because the data is
// not consistently spaced — "+852 90191713" and "+34.91.048.0666" both put the
// whole subscriber number in what a space-split would call the second field, and
// would ship unmasked.
export const maskPhone = (number) => {
	const hide = (run, keep = 0) => run.slice(0, keep) + '\u2022'.repeat(Math.max(0, run.length - keep))
	const runs = number.match(/\d+/g) ?? []

	// Nothing to split on: keep the country code and hide the rest.
	if (runs.length < 2) return number.replace(/\d+/g, (run) => hide(run, 3))

	// With only two runs the second one is the subscriber number itself, so one
	// stays visible instead of two.
	const visible = runs.length > 2 ? 2 : 1
	let index = 0
	return number.replace(/\d+/g, (run) => (index++ < visible ? run : hide(run)))
}

// Single-line address for card summaries and map popups.
export const summarise = (office) => [office.city, office.countryLabel, office.postcode].filter(Boolean).join(', ')

